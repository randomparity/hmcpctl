from __future__ import annotations

import re
from typing import Literal

from ..xmlutil import escapes_string_arguments
from .common import document_envelope

# chhwres documents a virtual Ethernet mac_addr as 12 hexadecimal characters
# (hmc-commands chhwres -a), and the HMC prints MACs that way (#1202).
_MAC_ADDRESS = re.compile(r"[0-9A-Fa-f]{12}")


def _adapter_document(
    root_element: str,
    partition_id_field: tuple[str, str],
    slot_field: tuple[str, str],
    vios_partition_id: int,
    vios_slot: int,
    slot_number: int | None = None,
) -> str:
    """Build a virtual client adapter document from the shared skeleton.

    *partition_id_field* / *slot_field* are ``(element, kb)`` pairs for the
    VIOS-side remote fields, which differ per adapter type (vSCSI vs vFC).
    The client VirtualSlotNumber is emitted only when *slot_number* is given;
    the HMC auto-assigns it otherwise.
    """
    (id_name, id_kb), (slot_name, slot_kb) = partition_id_field, slot_field
    slot = ""
    if slot_number is not None:
        slot = f'  <VirtualSlotNumber kb="COD" kxe="false">{slot_number}</VirtualSlotNumber>\n'
    body = f"""  <Metadata><Atom/></Metadata>
  <AdapterType kb="ROR" kxe="false">Client</AdapterType>
{slot}  <{id_name} kb="{id_kb}" kxe="false">{vios_partition_id}</{id_name}>
  <{slot_name} kb="{slot_kb}" kxe="false">{vios_slot}</{slot_name}>"""
    return document_envelope(root_element, body)


@escapes_string_arguments
def build_vscsi_adapter_document(
    vios_partition_id: int,
    vios_slot: int,
    slot_number: int | None = None,
) -> str:
    """Virtual SCSI client adapter, paired to a VIOS server adapter.

    vios_partition_id / vios_slot identify the VIOS and its server-side slot
    that own the backing storage. slot_number is the client adapter's virtual
    slot (auto-assigned by the HMC if omitted).
    """
    return _adapter_document(
        "VirtualSCSIClientAdapter",
        ("RemoteLogicalPartitionID", "CUR"),
        ("RemoteSlotNumber", "CUA"),
        vios_partition_id,
        vios_slot,
        slot_number,
    )


@escapes_string_arguments
def build_vfc_adapter_document(
    vios_partition_id: int,
    vios_slot: int,
    slot_number: int | None = None,
) -> str:
    """Virtual Fibre Channel (NPIV) client adapter, paired to a VIOS.

    ConnectingPartitionID / ConnectingVirtualSlotNumber identify the VIOS and
    its server-side FC slot. The WWPNs are generated by the HMC on creation.
    """
    return _adapter_document(
        "VirtualFibreChannelClientAdapter",
        # No live V10R3 kb value is recorded for these two fields (#961).
        ("ConnectingPartitionID", "CUD"),
        ("ConnectingVirtualSlotNumber", "CUD"),
        vios_partition_id,
        vios_slot,
        slot_number,
    )


def _require_network_integer(name: str, value: object, low: int, high: int) -> None:
    if value is not None and (
        isinstance(value, bool)
        or not isinstance(value, int)
        or not low <= value <= high
    ):
        raise ValueError(f"{name} must be an integer from {low} to {high}")


def validate_network_adapter_creation_fields(
    *,
    tagged: bool,
    addl_vlan_ids: list[int] | None = None,
    allowed_os_mac_addrs: list[str] | Literal["all", "none"] | None = None,
    qos_priority: int | Literal["none"] | None = None,
    vsi_manager_id: int | None = None,
    vsi_type_id: int | None = None,
    vsi_type_version: int | None = None,
) -> None:
    """Validate the bounded optional client Ethernet creation policies (#1821)."""
    if addl_vlan_ids is not None:
        if not isinstance(addl_vlan_ids, list) or len(addl_vlan_ids) > 20:
            raise ValueError("addl_vlan_ids must be a list of at most twenty VLAN IDs")
        for value in addl_vlan_ids:
            _require_network_integer("addl_vlan_ids", value, 1, 4094)
            if value is None:
                raise ValueError("addl_vlan_ids must contain integers from 1 to 4094")
        if addl_vlan_ids and tagged is not True:
            raise ValueError("nonempty addl_vlan_ids requires tagged=True")
    if allowed_os_mac_addrs is not None:
        valid = allowed_os_mac_addrs in ("all", "none")
        if isinstance(allowed_os_mac_addrs, list):
            valid = 1 <= len(allowed_os_mac_addrs) <= 4 and all(
                isinstance(value, str) and _MAC_ADDRESS.fullmatch(value)
                for value in allowed_os_mac_addrs
            )
        if not valid:
            raise ValueError(
                "allowed_os_mac_addrs must be all, none, or one to four 12-hex MAC addresses"
            )
    if qos_priority != "none":
        _require_network_integer("qos_priority", qos_priority, 0, 7)
    for name, value in (
        ("vsi_manager_id", vsi_manager_id),
        ("vsi_type_id", vsi_type_id),
        ("vsi_type_version", vsi_type_version),
    ):
        _require_network_integer(name, value, -(2**31), 2**31 - 1)


def validate_network_adapter_update_fields(
    *,
    tagged: bool | None = None,
    addl_vlan_ids: list[int] | None = None,
    vlan_action: Literal["replace", "add", "remove"] = "replace",
    qos_priority: int | Literal["none"] | None = None,
    vsi_manager_id: int | None = None,
    vsi_type_id: int | None = None,
    vsi_type_version: int | None = None,
    remove_vsi_profile: bool = False,
) -> None:
    """Validate explicit running-client settings; baseline rules belong to the operation."""
    if tagged is not None and type(tagged) is not bool:
        raise ValueError("tagged must be a boolean or omitted")
    if type(remove_vsi_profile) is not bool:
        raise ValueError("remove_vsi_profile must be a boolean")
    if vlan_action not in ("replace", "add", "remove"):
        raise ValueError("vlan_action must be replace, add or remove")
    if addl_vlan_ids is None and vlan_action != "replace":
        raise ValueError("vlan_action requires explicit addl_vlan_ids")
    if addl_vlan_ids is not None:
        if not isinstance(addl_vlan_ids, list):
            raise ValueError("addl_vlan_ids must be a list of integer VLAN IDs")
        for value in addl_vlan_ids:
            _require_network_integer("addl_vlan_ids", value, 1, 4094)
            if value is None:
                raise ValueError("addl_vlan_ids must contain integers from 1 to 4094")
        if len(set(addl_vlan_ids)) != len(addl_vlan_ids):
            raise ValueError("addl_vlan_ids must not contain duplicates")
        if vlan_action != "remove" and len(addl_vlan_ids) > 20:
            raise ValueError("the resulting VLAN set must contain at most twenty IDs")
        if vlan_action != "replace" and not addl_vlan_ids:
            raise ValueError("VLAN add/remove requires a nonempty list")
    if qos_priority != "none":
        _require_network_integer("qos_priority", qos_priority, 0, 7)
    vsi = (
        ("vsi_manager_id", vsi_manager_id),
        ("vsi_type_id", vsi_type_id),
        ("vsi_type_version", vsi_type_version),
    )
    for name, value in vsi:
        _require_network_integer(name, value, -(2**31), 2**31 - 1)
    if remove_vsi_profile and any(value is not None for _, value in vsi):
        raise ValueError(
            "VSI profile removal cannot be combined with numeric VSI settings"
        )
    if not remove_vsi_profile and all(
        value is None
        for value in (tagged, addl_vlan_ids, qos_priority, *(value for _, value in vsi))
    ):
        raise ValueError("select at least one network adapter update setting")


@escapes_string_arguments
def build_client_network_adapter_document(
    port_vlan_id: int,
    slot_number: int | None = None,
    virtual_switch_id: int | None = None,
    tagged: bool = False,
    mac_address: str | None = None,
    *,
    addl_vlan_ids: list[int] | None = None,
    allowed_os_mac_addrs: list[str] | Literal["all", "none"] | None = None,
    qos_priority: int | Literal["none"] | None = None,
    vsi_manager_id: int | None = None,
    vsi_type_id: int | None = None,
    vsi_type_version: int | None = None,
) -> str:
    """Virtual Ethernet client network adapter.

    port_vlan_id is the PVID (the VLAN the adapter sits on). virtual_switch_id
    selects a specific vSwitch (default switch used if omitted). tagged=True
    makes this a tagged (VLAN-trunking) adapter; mac_address pins the MAC
    (otherwise the HMC generates one).
    """
    validate_network_adapter_creation_fields(
        tagged=tagged,
        addl_vlan_ids=addl_vlan_ids,
        allowed_os_mac_addrs=allowed_os_mac_addrs,
        qos_priority=qos_priority,
        vsi_manager_id=vsi_manager_id,
        vsi_type_id=vsi_type_id,
        vsi_type_version=vsi_type_version,
    )
    if mac_address and not _MAC_ADDRESS.fullmatch(mac_address):
        raise ValueError(
            f"mac_address {mac_address!r} must be 12 hexadecimal digits with "
            "no separators, for example 020000000001"
        )
    # Element order and kb follow the served VirtualEthernetAdapter schema (#1399);
    # V10R3 refuses an out-of-order document with REST0001.
    parts = ["  <Metadata><Atom/></Metadata>"]
    if slot_number is not None:
        parts.append(
            f'  <VirtualSlotNumber kb="COD" kxe="false">{slot_number}</VirtualSlotNumber>'
        )
    if allowed_os_mac_addrs is not None:
        mac_policy = (
            allowed_os_mac_addrs.upper()
            if isinstance(allowed_os_mac_addrs, str)
            else " ".join(value.upper() for value in allowed_os_mac_addrs)
        )
        parts.append(
            f'  <AllowedOperatingSystemMACAddresses kb="CUD" kxe="false">'
            f"{mac_policy}</AllowedOperatingSystemMACAddresses>"
        )
    if mac_address:
        parts.append(f'  <MACAddress kb="CUR" kxe="false">{mac_address}</MACAddress>')
    parts.append(f'  <PortVLANID kb="CUR" kxe="false">{port_vlan_id}</PortVLANID>')
    if qos_priority is not None:
        if qos_priority != "none":
            parts.append(
                f'  <QualityOfServicePriority kb="CUD" kxe="false">'
                f"{qos_priority}</QualityOfServicePriority>"
            )
        enabled = "false" if qos_priority == "none" else "true"
        parts.append(
            f'  <QualityOfServicePriorityEnabled kb="CUD" kxe="false">'
            f"{enabled}</QualityOfServicePriorityEnabled>"
        )
    if addl_vlan_ids is not None:
        vlans = " ".join(str(value) for value in addl_vlan_ids)
        parts.append(f'  <TaggedVLANIDs kb="CUA" kxe="false">{vlans}</TaggedVLANIDs>')
    if tagged:
        parts.append(
            '  <TaggedVLANSupported kb="CUA" kxe="false">true</TaggedVLANSupported>'
        )
    for name, value in (
        ("VirtualStationInterfaceManagerID", vsi_manager_id),
        ("VirtualStationInterfaceTypeID", vsi_type_id),
    ):
        if value is not None:
            parts.append(f'  <{name} kb="CUD" kxe="false">{value}</{name}>')
    if virtual_switch_id is not None:
        parts.append(
            f'  <VirtualSwitchID kb="ROR" kxe="false">{virtual_switch_id}</VirtualSwitchID>'
        )
    if vsi_type_version is not None:
        parts.append(
            f'  <VirtualStationInterfaceTypeVersion kb="CUD" kxe="false">'
            f"{vsi_type_version}</VirtualStationInterfaceTypeVersion>"
        )
    body = "\n".join(parts)
    return document_envelope("ClientNetworkAdapter", body)


